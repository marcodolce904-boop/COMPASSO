export const STRINGS: Record<Lang, Record<StringKey, string>> = { en, it };

export type Params = Record<string, string | number>;

/** Testo tradotto con sostituzione dei parametri `{nome}`. */
export function t(lang: Lang, key: StringKey, params: Params = {}): string {
  const s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k: string) => (k in params ? String(params[k]) : m));
}

/** Numero nella forma della lingua (virgola decimale in italiano). */
export function num(lang: Lang, v: number, digits = 1): string {
  const s = v.toFixed(digits);
  return lang === 'it' ? s.replace('.', ',') : s;
}

/** Conteggio con singolare/plurale: `count('it', 'path', 1)` → «1 tracciato». */
export function count(
  lang: Lang,
  noun: 'path' | 'circle' | 'ellipse' | 'line' | 'arc',
  n: number,
): string {
  return t(lang, `n.${noun}.${n === 1 ? 'one' : 'other'}`, { n });
}

/** Riepilogo «23 tracciati · 5 cerchi, 12 linee» (§4.2 A). */
export function statsText(
  lang: Lang,
  s: { paths: number; circles: number; ellipses?: number; lines: number },
  /** Archi di costruzione delle curve libere. */
  arcs = 0,
): string {
  const ov =
    (s.ellipses ? `, ${count(lang, 'ellipse', s.ellipses)}` : '') +
    (arcs ? `, ${count(lang, 'arc', arcs)}` : '');
  return t(lang, 'preview.stats', {
    p: count(lang, 'path', s.paths),
    c: count(lang, 'circle', s.circles) + ov,
    l: count(lang, 'line', s.lines),
  });
}
